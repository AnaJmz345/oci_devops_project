-- Ejecutar en Oracle Database Actions conectado al esquema VANTAGE.
-- Si el esquema no es VANTAGE, ajustar los prefijos.

CREATE TABLE VANTAGE.BOT_INTENTS (
    INTENT_KEY              VARCHAR2(80) PRIMARY KEY,
    DESCRIPTION             VARCHAR2(500) NOT NULL,
    INTERNAL_ACTION         VARCHAR2(120) NOT NULL,
    PARAMETERS_SCHEMA       CLOB CHECK (PARAMETERS_SCHEMA IS JSON),
    ALLOWED_ROLE            VARCHAR2(50) DEFAULT 'USER' NOT NULL,
    REQUIRES_CONFIRMATION   CHAR(1) DEFAULT 'N' CHECK (REQUIRES_CONFIRMATION IN ('Y','N')),
    ACTIVE                  CHAR(1) DEFAULT 'Y' CHECK (ACTIVE IN ('Y','N')),
    CREATED_AT              TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP
);

CREATE TABLE VANTAGE.BOT_INTENT_EXAMPLES (
    EXAMPLE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INTENT_KEY      VARCHAR2(80) NOT NULL,
    EXAMPLE_TEXT    VARCHAR2(1000) NOT NULL,
    LANGUAGE_CODE   VARCHAR2(10) DEFAULT 'es' NOT NULL,
    ACTIVE          CHAR(1) DEFAULT 'Y' CHECK (ACTIVE IN ('Y','N')),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_BOT_INTENT_EXAMPLES_INTENT
        FOREIGN KEY (INTENT_KEY) REFERENCES VANTAGE.BOT_INTENTS (INTENT_KEY)
);

CREATE TABLE VANTAGE.BOT_INTENT_EMBEDDINGS (
    EMBEDDING_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EXAMPLE_ID          NUMBER NOT NULL,
    EMBEDDING_MODEL     VARCHAR2(200) NOT NULL,
    EMBEDDING_PROVIDER  VARCHAR2(50) DEFAULT 'LOCAL' NOT NULL,
    EMBEDDING_VECTOR    VECTOR(384, FLOAT32),
    EMBEDDING_JSON      CLOB CHECK (EMBEDDING_JSON IS JSON),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_BOT_INTENT_EMBEDDINGS_EXAMPLE
        FOREIGN KEY (EXAMPLE_ID) REFERENCES VANTAGE.BOT_INTENT_EXAMPLES (EXAMPLE_ID)
);

CREATE TABLE VANTAGE.BOT_CONVERSATION_CONTEXT (
    CONTEXT_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TELEGRAM_CHAT_ID        NUMBER NOT NULL,
    TELEGRAM_USERNAME       VARCHAR2(255),
    PENDING_INTENT_KEY      VARCHAR2(80),
    PENDING_ACTION          VARCHAR2(120),
    PARAMETERS_JSON         CLOB CHECK (PARAMETERS_JSON IS JSON),
    ORIGINAL_MESSAGE        CLOB,
    STATUS                  VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    EXPIRES_AT              TIMESTAMP,
    CREATED_AT              TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP,
    CONSTRAINT FK_BOT_CONTEXT_INTENT
        FOREIGN KEY (PENDING_INTENT_KEY) REFERENCES VANTAGE.BOT_INTENTS (INTENT_KEY)
);

CREATE TABLE VANTAGE.BOT_ACTION_AUDIT (
    AUDIT_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TELEGRAM_CHAT_ID    NUMBER,
    TELEGRAM_USERNAME   VARCHAR2(255),
    ORIGINAL_MESSAGE    CLOB,
    NORMALIZED_MESSAGE  CLOB,
    INTENT_KEY          VARCHAR2(80),
    CONFIDENCE          NUMBER(8,6),
    MATCHED_EXAMPLE     VARCHAR2(1000),
    PARAMETERS_JSON     CLOB CHECK (PARAMETERS_JSON IS JSON),
    ACTION_STATUS       VARCHAR2(30) NOT NULL,
    RESPONSE_MESSAGE    CLOB,
    ERROR_MESSAGE       CLOB,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
